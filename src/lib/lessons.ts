export type LessonSection = {
  heading: string;
  body: string[]; // پاراگراف‌های متن
  bullets?: string[]; // لیست نکات اختیاری
  example?: string; // مثال کاربردی اختیاری
};

export type Lesson = {
  id: string; // مثل "candles-1"
  category: LessonCategory;
  title: string;
  description: string;
  duration: number; // دقیقه
  difficulty: "مبتدی" | "متوسط" | "حرفه‌ای";
  sections: LessonSection[]; // ۳ تا ۵ سکشن
  keyTakeaways: string[]; // ۲ تا ۴ نکته کلیدی
};

export type LessonCategory = {
  id: string;
  title: string;
  description: string;
  icon: string; // یکی از: "candles" | "indicators" | "money" | "psychology"
  lessons: Lesson[];
};

type LessonSeed = Omit<Lesson, "category">;

/**
 * هر درس به دسته خودش ارجاع دارد و هر دسته به درس‌هایش؛
 * برای ساختن این ساختار حلقوی، ابتدا دسته ساخته می‌شود
 * و سپس فیلد category به هر درس متصل می‌گردد.
 */
function createCategory(
  input: Omit<LessonCategory, "lessons">,
  seeds: LessonSeed[],
): LessonCategory {
  const category: LessonCategory = { ...input, lessons: [] };
  category.lessons = seeds.map((seed) => ({ ...seed, category }));
  return category;
}

